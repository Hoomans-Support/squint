/* Shared data layer for every Squint page. Reads SQ.data (results.json, written by the pipeline, never hand-edited).
   Pages add their own selectors in sq/data-<page>.js; do not edit this file from a page lane, ask the shell owner.
   Everything shown must come from results.json: if a number is not there, show "n/a" or a Mock data tag, never invent it. */
(function () {
  'use strict';
  const SQ = window.SQ;

  /* ---- scope: shared by every page's scope bar and kept while the visitor moves between pages ---- */
  SQ.scope = { range: '7d', persona: 'all', platform: 'all' };
  SQ.RANGES = { '24h': { label: 'Last 24 hours', short: 'Last 24h', days: 1 }, '7d': { label: 'Last 7 days', short: 'Last 7 days', days: 7 }, '30d': { label: 'Last 30 days', short: 'Last 30 days', days: 30 } };
  SQ.setScope = (patch) => { Object.assign(SQ.scope, patch); SQ.redraw(); };

  /* ---- visitor settings: theme, currency, alert filter. Saved to localStorage so they survive a reload (per visitor, not shared). ---- */
  const SETTINGS_KEY = 'sq.settings';
  const DEFAULT_SETTINGS = { theme: 'light', currency: 'both', alertsCriticalOnly: false };
  SQ.settings = Object.assign({}, DEFAULT_SETTINGS);
  try {
    const saved = JSON.parse(localStorage.getItem(SETTINGS_KEY) || '{}');
    Object.assign(SQ.settings, saved);
  } catch (_) { /* private mode or blocked storage: defaults only, for this visit */ }
  const applyTheme = () => { try { document.documentElement.setAttribute('data-theme', SQ.settings.theme); } catch (_) { /* no document yet */ } };
  applyTheme();
  SQ.setSetting = (key, value) => {
    SQ.settings[key] = value;
    try { localStorage.setItem(SETTINGS_KEY, JSON.stringify(SQ.settings)); } catch (_) { /* session-only preference is optional */ }
    if (key === 'theme') applyTheme();
    SQ.redraw();
  };

  /* ---- formatting ---- */
  SQ.fmt = (n) => (n == null || Number.isNaN(Number(n)) ? 'n/a' : Number(n).toLocaleString('en-US'));
  const USD_PER_PHP = 1 / 56;   // fixed approximate rate for this demo, not a live FX feed; always labelled "approx"
  SQ.money = (n) => {
    if (n == null) return 'n/a';
    const php = '₱' + Math.round(Number(n)).toLocaleString('en-US');
    if (SQ.settings.currency === 'usd') return '~$' + Math.round(Number(n) * USD_PER_PHP).toLocaleString('en-US');
    if (SQ.settings.currency === 'both') return php + ' (~$' + Math.round(Number(n) * USD_PER_PHP).toLocaleString('en-US') + ')';
    return php;
  };
  SQ.pct = (frac, d = 0) => (frac == null ? 'n/a' : (Number(frac) * 100).toFixed(d) + '%');
  SQ.pct1 = (v) => (v == null ? 'n/a' : Number(v).toFixed(1) + '%');   // for values already in percent units

  /* ---- selectors ---- */
  SQ.D = () => SQ.data;
  SQ.personas = () => SQ.data.scope.personas.filter((p) => p.id !== 'unknown' && p.id !== 'fraudster');
  SQ.personaIds = (id = SQ.scope.persona) => id === 'all' ? [] : String(id).split('+');
  SQ.personaLabel = (id) => {
    if (id === 'all') return 'All users';
    const names = String(id).split('+').map((pid) => (SQ.data.scope.personas.find((p) => p.id === pid) || {}).label || pid);
    if (names.length < 2) return names[0];
    return names.length === 2 ? names.join(' and ') : names.slice(0, -1).join(', ') + ', and ' + names[names.length - 1];
  };
  SQ.userCount = () => {
    const users = (p) => SQ.scope.platform === 'all' ? p.users : ((p.platform_users || {})[SQ.scope.platform] || 0);
    if (SQ.scope.persona === 'all') return SQ.personas().reduce((a, p) => a + users(p), 0);
    const selected = new Set(SQ.personaIds());
    return SQ.personas().reduce((a, p) => a + (selected.has(p.id) ? users(p) : 0), 0);
  };
  SQ.personaUserCount = (p) => SQ.scope.platform === 'all' ? p.users : ((p.platform_users || {})[SQ.scope.platform] || 0);
  SQ.viewKey = () => SQ.scope.range + '|' + SQ.scope.platform + '|' + SQ.scope.persona;
  SQ.view = () => {
    const view = SQ.data.views[SQ.viewKey()];
    if (!view) throw new Error('Missing results for scope ' + SQ.viewKey());
    return view;
  };
  SQ.insight = (id) => SQ.data.insights.find((i) => i.id === id);
  /* ---- "mark fixed": a visitor's own session-local note that a finding no longer needs attention. Kept in
     sessionStorage only (like Ask history), never sent anywhere, so it never hides a finding for anyone else.
     Stored as {id: isoDate} (not a plain id list) so the fixed date can be shown later. ---- */
  const FIXED_KEY = 'sq.fixedIds';
  let fixedMap = {};
  try {
    const saved = JSON.parse(sessionStorage.getItem(FIXED_KEY) || '{}');
    if (saved && typeof saved === 'object' && !Array.isArray(saved)) fixedMap = saved;
  } catch (_) { /* session-only, starts empty if storage is unavailable */ }
  SQ.isFixed = (id) => Object.prototype.hasOwnProperty.call(fixedMap, id);
  SQ.fixedDate = (id) => fixedMap[id] || null;
  SQ.markFixed = (id) => {
    fixedMap[id] = new Date().toISOString();
    try { sessionStorage.setItem(FIXED_KEY, JSON.stringify(fixedMap)); } catch (_) { /* this mark lasts for this visit only */ }
    SQ.toast('Marked fixed');
    SQ.redraw();
  };

  /* ---- "ticket created": same session-local, {id: isoDate} mechanism as Mark fixed above, so the
     drafted-ticket button still shows "Ticket created" after a reload in this tab. Unlike Mark fixed
     this never changes a finding's open/fixed status — it only remembers the button's own state. ---- */
  const CREATED_KEY = 'sq.createdTicketIds';
  let createdMap = {};
  try {
    const saved = JSON.parse(sessionStorage.getItem(CREATED_KEY) || '{}');
    if (saved && typeof saved === 'object' && !Array.isArray(saved)) createdMap = saved;
  } catch (_) { /* session-only, starts empty if storage is unavailable */ }
  SQ.isTicketCreated = (id) => Object.prototype.hasOwnProperty.call(createdMap, id);
  SQ.markTicketCreated = (id) => {
    createdMap[id] = new Date().toISOString();
    try { sessionStorage.setItem(CREATED_KEY, JSON.stringify(createdMap)); } catch (_) { /* this mark lasts for this visit only */ }
    SQ.redraw();
  };

  /* ---- a brief confirmation toast, outside the app's own render tree so it survives the redraw a caller
     like markFixed triggers right after showing it. ---- */
  let toastTimer = null;
  SQ.toast = (msg) => {
    const el = document.getElementById('sq-toast');
    if (!el) return;
    el.textContent = msg;
    el.classList.add('show');
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => el.classList.remove('show'), 2600);
  };
  /* the open problems for the current scope, worst first (critical, then warning), with a stable priority label P1, P2, ... */
  SQ.problems = () => {
    const order = { critical: 0, warning: 1, healthy: 2 };
    const all = SQ.data.insights.filter((i) => i.severity !== 'healthy' && !SQ.isFixed(i.id)).slice().sort((a, b) => (order[a.severity] - order[b.severity]) || ((b.impact || {}).score || 0) - ((a.impact || {}).score || 0));
    all.forEach((i, k) => { i.__p = 'P' + (k + 1); });
    const inView = new Set(SQ.view().insight_ids);
    return all.filter((i) => inView.has(i.id));
  };
  /* fixed findings for the current scope, most recently fixed first — shown greyed out at the bottom of
     "Other problems" instead of disappearing, but excluded from SQ.problems() so they don't count as open. */
  SQ.fixedProblems = () => {
    const inView = new Set(SQ.view().insight_ids);
    return SQ.data.insights
      .filter((i) => i.severity !== 'healthy' && SQ.isFixed(i.id) && inView.has(i.id))
      .sort((a, b) => (SQ.fixedDate(b.id) || '').localeCompare(SQ.fixedDate(a.id) || ''));
  };
  SQ.asOf = () => { const d = new Date(SQ.data.meta.as_of + 'T00:00:00Z'); return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' }); };
  SQ.rangeDates = () => {
    const end = new Date(SQ.data.meta.as_of + 'T00:00:00Z'); const start = new Date(end); start.setUTCDate(start.getUTCDate() - (SQ.RANGES[SQ.scope.range].days - 1));
    const f = (d) => d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', timeZone: 'UTC' });
    return f(start) + '–' + f(end).replace(/^\w+ /, (m) => (f(start).split(' ')[0] === m.trim() ? '' : m));
  };

  /* ---- chart grow-in on scroll: `.sq-grow-x`/`.sq-grow-y`/`.track > *`/`.sqa-track > *` (squint.css) start scaled
     to 0 and only animate once their section crosses the middle of the viewport, once per appearance. The
     component framework re-renders by replacing DOM nodes, so new chart elements keep appearing after the first
     page load; a MutationObserver picks those up instead of a one-time querySelectorAll. ---- */
  try {
    const GROW_SEL = '.sq-grow-x, .sq-grow-y, .track > *, .sqa-track > *, .sq-wipe';
    const io = new IntersectionObserver((entries) => {
      entries.forEach((e) => { if (e.isIntersecting) { e.target.classList.add('in-view'); io.unobserve(e.target); } });
    }, { threshold: 0.2 });   // a chart already on screen at load fires right away (IntersectionObserver checks on observe());
                              // one scrolled into view fires once a fifth of it is visible, not only exactly mid-viewport
    const watch = (root) => {
      if (root.nodeType !== 1) return;
      if (root.matches && root.matches(GROW_SEL) && !root.classList.contains('in-view')) io.observe(root);
      root.querySelectorAll && root.querySelectorAll(GROW_SEL).forEach((el) => { if (!el.classList.contains('in-view')) io.observe(el); });
    };
    new MutationObserver((muts) => muts.forEach((m) => m.addedNodes.forEach(watch))).observe(document.documentElement, { childList: true, subtree: true });
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => watch(document.body));
    else watch(document.body);
  } catch (_) { /* no IntersectionObserver (very old browser): charts keep their scaled-to-0 base style, acceptable degrade */ }

  /* ---- "i" info circles (.ds-context, a native <details>) open on hover/focus, not only a click. A closed
     <details>'s non-summary content is kept out of the render tree by the browser itself, so this has to set
     the real `open` attribute rather than a CSS-only show/hide (see squint.css for what was tried first and
     why it didn't paint). pointerover/pointerout and focusin/focusout all bubble, so one delegated listener
     covers every .ds-context on every page, including ones added later by a re-render. ---- */
  const dsCtx = (t) => t && t.closest && t.closest('.ds-context');
  document.addEventListener('pointerover', (e) => { const c = dsCtx(e.target); if (c) c.open = true; });
  document.addEventListener('pointerout', (e) => { const c = dsCtx(e.target); if (c && !c.contains(e.relatedTarget)) c.open = false; });
  document.addEventListener('focusin', (e) => { const c = dsCtx(e.target); if (c) c.open = true; });
  document.addEventListener('focusout', (e) => { const c = dsCtx(e.target); if (c && !c.contains(e.relatedTarget)) c.open = false; });
})();
